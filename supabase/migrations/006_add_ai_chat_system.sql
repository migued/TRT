-- Function to update conversation updated_at and last_message_at
create or replace function update_ai_conversation_on_message()
returns trigger as $$
begin
  update ai_conversations
  set
    updated_at = now(),
    last_message_at = now(),
    message_count = message_count + 1,
    total_tokens_used = total_tokens_used + new.total_tokens,
    total_cost = total_cost + new.cost
  where id = new.conversation_id;

  return new;
end;
$$ language plpgsql;

-- Trigger for updating conversation on new message
create trigger update_ai_conversation_on_message_trigger
  after insert on ai_messages
  for each row
  execute function update_ai_conversation_on_message();

-- Function to update/create usage tracking
create or replace function track_ai_usage(
  p_user_id uuid,
  p_workspace_id uuid,
  p_tokens int,
  p_cost decimal
)
returns void as $$
declare
  v_month text;
begin
  v_month := to_char(now(), 'YYYY-MM');

  insert into ai_usage_tracking (user_id, workspace_id, month, total_messages, total_tokens, total_cost)
  values (p_user_id, p_workspace_id, v_month, 1, p_tokens, p_cost)
  on conflict (user_id, workspace_id, month)
  do update set
    total_messages = ai_usage_tracking.total_messages + 1,
    total_tokens = ai_usage_tracking.total_tokens + p_tokens,
    total_cost = ai_usage_tracking.total_cost + p_cost,
    updated_at = now();
end;
$$ language plpgsql;

