-- AI Chat Conversations Table
create table if not exists ai_conversations (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid references workspaces(id) on delete cascade not null,
  user_id uuid references auth.users(id) on delete cascade not null,

  -- Conversation metadata
  title text, -- Auto-generated by AI, can be null initially
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  last_message_at timestamptz default now(),

  -- Message count and usage
  message_count int default 0,
  total_tokens_used int default 0,
  total_cost decimal(10, 6) default 0
);

-- AI Chat Messages Table
create table if not exists ai_messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid references ai_conversations(id) on delete cascade not null,

  -- Message content
  role text not null check (role in ('user', 'assistant', 'system')),
  content text not null,

  -- Reasoning tokens (for deepseek-r1 and similar models)
  reasoning text, -- The thinking/reasoning process
  reasoning_details jsonb, -- Structured reasoning details from API

  -- Token usage tracking
  input_tokens int default 0,
  output_tokens int default 0,
  reasoning_tokens int default 0,
  total_tokens int default 0,
  cost decimal(10, 6) default 0,

  -- Model used
  model text default 'deepseek/deepseek-r1',

  -- Timestamps
  created_at timestamptz default now(),

  -- Order in conversation
  sequence_number int not null
);

-- AI File Attachments Table
create table if not exists ai_file_attachments (
  id uuid primary key default gen_random_uuid(),
  message_id uuid references ai_messages(id) on delete cascade not null,

  -- File metadata
  file_name text not null,
  file_type text not null, -- 'pdf', 'excel', 'word', 'image'
  file_size int not null, -- in bytes
  mime_type text not null,

  -- Storage
  storage_path text not null, -- Path in Supabase storage
  storage_url text, -- Public or signed URL

  -- Extracted content (for processing)
  extracted_text text, -- For PDFs, Word docs
  extracted_data jsonb, -- For Excel, structured data
  preview_url text, -- For images, preview thumbnails

  -- Processing status
  processing_status text default 'pending' check (processing_status in ('pending', 'processing', 'completed', 'failed')),
  extraction_model text, -- Model used for extraction (e.g., 'qwen/qwen-2.5-vl-32b-instruct')

  created_at timestamptz default now()
);

-- AI Usage Tracking Table (per user per month)
create table if not exists ai_usage_tracking (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade not null,
  workspace_id uuid references workspaces(id) on delete cascade not null,

  -- Time period (format: YYYY-MM)
  month text not null, -- e.g., '2025-01'

  -- Usage metrics
  total_messages int default 0,
  total_tokens int default 0,
  total_cost decimal(10, 4) default 0,

  -- File processing usage
  files_processed int default 0,

  -- Limits (soft limits)
  message_limit int default 1000, -- Soft limit per month
  token_limit int default 1000000, -- Soft limit per month

  -- Warning flags
  warning_shown boolean default false,

  created_at timestamptz default now(),
  updated_at timestamptz default now(),

  -- Unique constraint per user per month
  unique(user_id, workspace_id, month)
);

-- Indexes for performance
create index if not exists idx_ai_conversations_workspace on ai_conversations(workspace_id);
create index if not exists idx_ai_conversations_user on ai_conversations(user_id);
create index if not exists idx_ai_conversations_updated on ai_conversations(last_message_at desc);

create index if not exists idx_ai_messages_conversation on ai_messages(conversation_id, sequence_number);
create index if not exists idx_ai_messages_created on ai_messages(created_at);

create index if not exists idx_ai_files_message on ai_file_attachments(message_id);
create index if not exists idx_ai_files_status on ai_file_attachments(processing_status);

create index if not exists idx_ai_usage_user_month on ai_usage_tracking(user_id, month);
create index if not exists idx_ai_usage_workspace on ai_usage_tracking(workspace_id, month);

